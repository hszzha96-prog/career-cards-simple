"""岗位小镇的原创像素图：用 ASCII 网格手绘，转成 SVG 路径。

ICONS：12×12 公司图标，# 为主色（白），+ 为点缀色（奶油）。
新增图标：照下面的格式加一项，名字在 data/dashboard.json 里引用。
CROPS：16×16 作物六个阶段（种子、发芽、长叶、含苞、开花、枯萎）。
"""

def runs(rows, ch, size):
    d = []
    for y, row in enumerate(rows):
        row = row.ljust(size, '.')[:size]
        x = 0
        while x < size:
            if row[x] == ch:
                s = x
                while x < size and row[x] == ch:
                    x += 1
                d.append('M%d %dh%dv1h-%dz' % (s, y, x - s, x - s))
            else:
                x += 1
    return ''.join(d)

def icon(rows):
    rows = [r for r in rows if r is not None]
    return {'a': runs(rows, '#', 12), 'b': runs(rows, '+', 12)}

